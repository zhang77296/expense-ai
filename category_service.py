# category_service.py
# 消费分类体系与关键词映射

CATEGORIES = ["餐饮", "交通", "购物", "娱乐", "住房", "医疗", "教育", "其他"]

KEYWORDS = {
    "餐饮": ["饭", "午餐", "晚餐", "早餐", "咖啡", "奶茶", "外卖", "餐厅", "火锅", "烧烤", "食堂", "星巴克"],
    "交通": ["打车", "地铁", "公交", "高铁", "机票", "加油", "停车", "滴滴", "出租"],
    "购物": ["淘宝", "京东", "超市", "衣服", "鞋", "日用品", "拼多多", "商场"],
    "娱乐": ["电影", "游戏", "KTV", "演出", "演唱会", "会员", "视频", "爱奇艺"],
    "住房": ["房租", "水电", "物业", "燃气", "宽带", "住宿", "酒店"],
    "医疗": ["医院", "药", "挂号", "体检", "诊所"],
    "教育": ["书", "课程", "培训", "学费", "考试"],
}

def normalize_category(raw=None, merchant=None, note=None, text=None):
    """
    将原始输入、商户、备注等文本映射到标准分类。
    如果有 LLM 给出的分类且在枚举内，优先使用；否则通过关键词匹配。
    """
    # 如果传入的分类已经在标准枚举里，直接用
    if raw in CATEGORIES:
        return raw
    
    # 把所有文本拼起来做关键词匹配
    blob = " ".join(str(x) for x in [raw, merchant, note, text] if x)
    
    for cat, kws in KEYWORDS.items():
        if any(k in blob for k in kws):
            return cat
            
    # 匹配不到就归入“其他”
    return "其他"